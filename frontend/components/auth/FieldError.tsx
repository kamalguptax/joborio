/** Inline error under a form field. Pair the input with aria-invalid + aria-describedby={id}. */
export default function FieldError({ id, message }: { id?: string; message?: string }) {
  if (!message) return null;
  return (
    <p id={id} role="alert" className="mt-1 text-xs font-medium text-red-600">
      {message}
    </p>
  );
}
